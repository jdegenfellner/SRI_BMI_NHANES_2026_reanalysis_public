#!/usr/bin/env python3
# Rechenzeit der Ableitung aus den Done-Markern (prep_min, ggir_min fuer GGIR; prep_s, swan_s fuer SWaN) und den Herkunftsprotokollen.
# Ausgabe: je Plattform Anzahl Teilnehmer, mediane und summierte Rechenzeit (Stunden), sowie die Kalenderspanne (erste bis letzte Fertigstellung).
# Aufruf: python3 compute_timing_summary.py [RAW_ROOT]   (Standard: /Volumes/LaCie/NHANES_1112_1314)
import os, sys, statistics as st, datetime as dt, collections
raw = sys.argv[1] if len(sys.argv) > 1 else "/Volumes/LaCie/NHANES_1112_1314"
rank_max = int(os.environ.get("RANK_MAX", "0"))        # 0 = all processed participants; else only ranks <= RANK_MAX of analytic_random_order.tsv
tex_out = os.environ.get("TEX_OUT", "")                # optional: write LaTeX macros (\rawCompute...) to this file
order = {l.split("\t")[1]: int(l.split("\t")[0]) for l in open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "analytic_random_order.tsv")).read().splitlines()[1:]}
if rank_max: order = {k: v for k, v in order.items() if v <= rank_max}
origin = {}
p = f"{raw}/_work/cloud_ingested.log"
if os.path.exists(p):
    for l in open(p):
        q = l.split()
        if len(q) > 3:
            src = q[3].split("/")[0]
            origin[q[1]] = "M1 Pro" if src == "m1pro" else "Hetzner" if src.startswith("hz") else "Vultr" if src.startswith("vu") else "AWS"
def meta(f):
    d = {}
    for l in open(f):
        k, _, v = l.rstrip("\n").partition("\t"); d[k] = v
    return d
rows = collections.defaultdict(list); stamps = []
for cyc in ("pax_g", "pax_h"):
    gdir = f"{raw}/_ggir/{cyc}/done"; sdir = f"{raw}/_swan/{cyc}/done"
    if not os.path.isdir(gdir): continue
    for f in os.listdir(gdir):
        if not f.endswith(".txt") or f.startswith("."): continue
        sq = f[:-4]
        if sq not in order or not os.path.exists(f"{sdir}/{f}"): continue
        try:
            g, s = meta(f"{gdir}/{f}"), meta(f"{sdir}/{f}")
            h = (float(g.get("prep_min", 0)) + float(g.get("ggir_min", 0))) / 60 + (float(s.get("prep_s", 0)) + float(s.get("swan_s", 0))) / 3600
        except Exception: continue
        rows[origin.get(sq, "MacBook M5 Max")].append(h)
        stamps.append(max(os.path.getmtime(f"{gdir}/{f}"), os.path.getmtime(f"{sdir}/{f}")))
tot = sum(sum(v) for v in rows.values()); n = sum(len(v) for v in rows.values())
print(f"{'Plattform':<16}{'n':>6}{'Median (min)':>14}{'Summe (h)':>11}")
for k, v in sorted(rows.items()): print(f"{k:<16}{len(v):>6}{60*st.median(v):>14.1f}{sum(v):>11.1f}")
print(f"{'gesamt':<16}{n:>6}{60*st.median([x for v in rows.values() for x in v]):>14.1f}{tot:>11.1f}")
if tex_out and stamps:
    med_all = 60 * st.median([x for v in rows.values() for x in v]); days = (max(stamps) - min(stamps)) / 86400
    lines = ["% generated by compute_timing_summary.py; do not edit", f"\\newcommand{{\\rawComputeN}}{{{n}}}", f"\\newcommand{{\\rawComputeDays}}{{{days:.1f}}}",
             f"\\newcommand{{\\rawComputeHours}}{{{tot:.0f}}}", f"\\newcommand{{\\rawComputeMedianMin}}{{{med_all:.0f}}}",
             f"\\newcommand{{\\rawComputeStart}}{{{dt.datetime.fromtimestamp(min(stamps)):%d %B %Y}}}", f"\\newcommand{{\\rawComputeEnd}}{{{dt.datetime.fromtimestamp(max(stamps)):%d %B %Y}}}"]
    key = {"MacBook M5 Max": "Mac", "M1 Pro": "MOne", "AWS": "Aws", "Hetzner": "Hetzner", "Vultr": "Vultr"}
    for k, v in rows.items(): lines += [f"\\newcommand{{\\rawCompute{key[k]}N}}{{{len(v)}}}", f"\\newcommand{{\\rawCompute{key[k]}Hours}}{{{sum(v):.0f}}}", f"\\newcommand{{\\rawCompute{key[k]}MedianMin}}{{{60*st.median(v):.0f}}}"]
    for k in key.values():
        if f"\\rawCompute{k}N" not in "".join(lines): lines += [f"\\newcommand{{\\rawCompute{k}N}}{{0}}", f"\\newcommand{{\\rawCompute{k}Hours}}{{0}}", f"\\newcommand{{\\rawCompute{k}MedianMin}}{{--}}"]
    open(tex_out, "w").write("\n".join(lines) + "\n")
if stamps: print("Kalenderspanne:", dt.datetime.fromtimestamp(min(stamps)).strftime("%d.%m.%Y %H:%M"), "bis", dt.datetime.fromtimestamp(max(stamps)).strftime("%d.%m.%Y %H:%M"), f"({(max(stamps)-min(stamps))/86400:.1f} Tage)")
